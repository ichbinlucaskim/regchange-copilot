"""지시 유도 패턴 스캔 — 외부 텍스트만, 탐지·기록만 한다 (기획서 10.1, R-23).

목적:
    모델에게 넘어가는 **외부 텍스트**에서 "지시를 유도하는" 형태를 찾아 신호로 남긴다.
    차단하지 않는다.

범위 (2026-08-21, R-23 ②):
    `scan` 은 `str` 이 아니라 `UntrustedText` 를 받는다. 사내 규정 문단으로는 그 타입을
    만들 수 없으므로 **trusted 텍스트가 이 함수에 도달하는 경로가 없다.** 그전에는
    조립이 끝난 프롬프트 전체를 훑었고, 그래서 사내 규정 제20조의 "비밀번호"가
    `TOOL_OR_KEY_SOLICITATION` 을 발화시켰다(R-23 관측).

    **감도는 바꾸지 않았다.** 패턴 목록도 정규식도 그대로다. 바뀐 것은 무엇을 훑는가뿐이며,
    그래야 재측정이 "범위 변경의 효과"만 재게 된다.

구현 이유:
    **차단 로직은 5단계다. 탐지는 지금 만든다.** 무엇을 차단해야 하는지는 실제로 무엇이
    탐지되는지를 본 뒤에 정해야 한다. 지금 차단 규칙을 만들면 관측 없이 만든 규칙이
    되고, 그 규칙이 정당한 법령 문언을 막았을 때 그 사실이 드러나지 않는다.

    **신호를 `llm_invocation.injection_signals_json` 에 남긴다.** 로그로만 남기면
    "이 출력은 신호가 있는 입력에서 나왔다"를 사후에 대조할 수 없다. 6개월 뒤 어떤 출력이
    이상하다고 판명됐을 때, 그 입력에 신호가 있었는지가 첫 번째 질문이다.

    **한국어와 영어를 함께 본다.** 법령 원문은 한국어지만 인젝션 시도가 한국어일 이유가
    없다. 첨부 문서나 사내 문서 경유 경로가 열리면 더욱 그렇다.

    **이 스캔은 방어가 아니다.** 실제 방어선은 원칙 5(LLM 프로세스는 읽기 전용 DB role)이며,
    인젝션이 성립하더라도 피해가 조회로 제한된다. 패턴 매칭은 우회하기 쉽고, 우회하기 쉬운
    것을 방어라고 부르면 실제 경계에 대한 투자가 줄어든다.

트레이드오프:
    - **오탐이 난다.** 법령 원문에 "지시"·"명령"·"따라야 한다" 같은 단어가 정상적으로
      등장한다. 차단하지 않고 기록만 하므로 오탐 비용이 낮고, 그래서 민감하게 잡는 쪽을
      택했다. **차단을 붙이는 5단계에서는 이 감도를 반드시 다시 재야 한다** — 지금
      감도로 차단하면 정상 조문이 막힌다.
    - 정규식 목록이라 새로운 표현을 놓친다. 미탐을 줄이려 목록을 키우면 오탐이 는다.
      이 균형은 실측 없이 정할 수 없고, 그래서 지금은 정하지 않는다.
    - 대소문자와 공백만 정규화한다. 유니코드 유사 문자(호모글리프)나 인코딩 변형은 보지
      않는다. 그 수준의 회피를 상정한다면 패턴 매칭 자체가 답이 아니다.

엣지 케이스:
    - 빈 문자열: 여기까지 오지 않는다. `guards.trust.from_regulation` 이 먼저 거부한다 —
      빈 입력을 스캔하면 "신호 없음"과 구별되지 않는다.
    - 같은 패턴이 여러 번: 신호를 한 번만 남긴다. 횟수는 지금 쓰이지 않으며, 쓰이지 않는
      값을 기록하면 그 값이 정확한지 아무도 확인하지 않는다.
    - 신호가 있어도 호출은 진행된다. 그것이 "탐지·기록만"의 의미다.
    - **블록 경계를 넘는 인젝션**: 보지 않는다. 조립된 문자열 전체를 훑던 이전 구현도
      그것을 노린 것이 아니었다(그 목적으로 설계된 적이 없다). 필요하다면 다른 방어이며,
      지금 이 함수에 얹으면 R-23 이 되돌아온다.
"""

from __future__ import annotations

import re

from regchange.guards.trust import UntrustedText

INJECTION_PATTERNS: tuple[tuple[str, str], ...] = (
    (
        "IGNORE_INSTRUCTIONS",
        r"(이전|위의|앞의|기존)\s*(지시|지침|규칙|명령)[^\n]{0,10}(무시|잊)"
        r"|ignore\s+(all\s+)?(previous|prior|above)\s+(instruction|prompt|rule)",
    ),
    (
        "ROLE_OVERRIDE",
        r"(너는|당신은|넌)\s*(이제|지금부터)"
        r"|you\s+are\s+now\s+"
        r"|act\s+as\s+(a|an)\s+",
    ),
    (
        "SYSTEM_PROMPT_PROBE",
        r"시스템\s*(프롬프트|지침|메시지)"
        r"|system\s+(prompt|instruction|message)"
        r"|reveal\s+your\s+",
    ),
    (
        "OUTPUT_FORMAT_OVERRIDE",
        r"(출력|응답|답변)\s*(형식|포맷)[^\n]{0,10}(무시|바꾸|변경)"
        r"|(대신|반드시)\s*[\"'`][^\"'`\n]{1,40}[\"'`]\s*(라고|만)\s*(출력|응답|답)",
    ),
    (
        "ROLE_MARKER_IN_DATA",
        r"^\s*(system|assistant|user)\s*:",
    ),
    (
        "TOOL_OR_KEY_SOLICITATION",
        r"(api\s*key|비밀번호|자격\s*증명|credential|access\s*token)"
        r"|(데이터베이스|db)\s*(에|에서)?\s*(삽입|수정|삭제|insert|update|delete)",
    ),
)
"""탐지 패턴 목록. 이름은 `injection_signals_json` 에 그대로 들어간다.

**이 목록은 방어 목록이 아니라 관측 목록이다.** 무엇이 실제로 나타나는지 보기 위한
것이며, 여기 없는 표현이 안전하다는 뜻이 아니다."""

_COMPILED = tuple(
    (name, re.compile(pattern, re.IGNORECASE | re.MULTILINE))
    for name, pattern in INJECTION_PATTERNS
)


def scan(block: UntrustedText) -> tuple[str, ...]:
    """외부 텍스트에서 지시 유도 패턴을 찾아 신호 이름을 돌려준다.

    목적:
        입력에 무엇이 있었는지를 호출 기록에 남길 수 있는 형태로 만든다.

    구현 이유:
        **인자 타입이 `str` 이 아니다.** 사내 문서 텍스트로는 `UntrustedText` 를 만들 수
        없으므로(`guards.trust`), trusted 텍스트가 이 함수에 도달하는 경로가 타입 수준에서
        없다. 호출부의 주의가 아니라 mypy strict 가 그것을 지킨다 (R-23 ②).

        신호 이름만 돌려주고 매칭된 문자열은 돌려주지 않는다. 매칭 문자열을 기록에 넣으면
        외부 텍스트 조각이 로그·DB 로 퍼지고, 그 조각이 다시 다른 프롬프트에 실릴 여지가
        생긴다. 원문은 스냅샷에 이미 있으므로 신호만으로 되짚을 수 있다.

    트레이드오프:
        어느 부분이 걸렸는지 즉시 알 수 없어 조사 시 원문을 다시 봐야 한다. 그 마찰을
        택한 이유는 위와 같다.

    엣지 케이스:
        모듈 docstring 참조. 정렬된 순서로 돌려주어 기록이 실행마다 흔들리지 않게 한다.
    """
    found = {name for name, pattern in _COMPILED if pattern.search(block.text)}
    return tuple(sorted(found))
