"""임베딩 호출 인터페이스. 모델 식별자와 차원을 계약에 포함한다.

목적:
    텍스트를 벡터로 바꾸는 최소 경계를 선언한다. 검색 계층은 이 Protocol 만 보고
    동작하며, 어느 공급자를 쓰는지 알지 못한다 (ADR-010).

구현 이유:
    **`model_id` 와 `dimensions` 를 인터페이스에 넣는다.** 임베딩은 모델이 바뀌면
    이전 벡터와 섞일 수 없는데, 그 사실이 타입에 드러나지 않으면 두 모델의 벡터가
    한 테이블에 들어가 조용히 비교된다. `policy_paragraph_embedding` 의 기본키가
    `(paragraph_id, model_id)` 인 것과 같은 방어이며, 여기서는 그 값을 어댑터가
    **스스로 알고 있어야** DB 에 적을 수 있다.

    **질의용과 문서용 메서드를 나눈다.** 다수의 검색 임베딩 모델이 비대칭이다 —
    질의와 문서에 다른 접두어나 다른 풀링을 쓴다. 하나로 합치면 그 차이를 호출부가
    기억해야 하고, 잊으면 점수가 조용히 나빠진다. 지금 쓰는 모델이 대칭이더라도
    경계는 비대칭을 허용하는 쪽으로 열어 둔다.

    **동기 인터페이스다.** `adapters/llm.py` 는 async 인데 여기는 아니다. 임베딩은
    (a) 적재 시점의 배치 작업이거나 (b) 질의당 1회이며, 로컬 모델 구현은 본질적으로
    CPU/GPU 바운드 동기 코드다. 그것을 `async` 로 감싸면 이벤트 루프를 막으면서
    비동기인 척하는 인터페이스가 된다. 거짓 비동기보다 정직한 동기가 낫다.

트레이드오프:
    배치 크기를 인터페이스가 정하지 않는다. 구현체가 자기 한계(API 요청당 입력 수,
    GPU 메모리)에 맞춰 쪼갠다. 호출부가 배치를 관리하면 공급자마다 다른 한계가
    도메인 코드로 새어 나온다. 그 대신 호출부는 진행률을 알 수 없다.

    반환 타입을 `tuple[float, ...]` 로 둔다. `numpy` 배열이 더 빠르지만, 도메인
    경계에서 numpy 를 요구하면 어댑터를 바꿔도 numpy 의존이 남는다.

엣지 케이스:
    - 빈 문자열 입력: 구현체가 예외를 던진다. 빈 입력의 벡터는 의미가 없고, 조용히
      영벡터를 돌려주면 코사인 거리가 정의되지 않아 순위가 임의로 정해진다.
    - 입력이 모델 최대 토큰을 넘음: 구현체가 자르되 **자른 사실을 로그에 남긴다.**
      조용한 절단은 "왜 이 문단이 안 잡히지"의 원인이 되고 추적이 어렵다.
    - 반환 차원이 `dimensions` 와 다름: 구현체가 예외를 던진다. DB 의 CHECK 제약이
      다시 한 번 잡지만, 그 전에 실패하는 편이 원인 추적이 쉽다.
    - 이 인터페이스는 킬 스위치를 검사하지 않는다. 검사는 `guards` 가 하며, 두 곳에서
      하면 한쪽이 갱신되지 않았을 때 우회 경로가 생긴다 (`adapters/llm.py` 와 같은 판단).
"""

from __future__ import annotations

from collections.abc import Sequence
from typing import Protocol

type Vector = tuple[float, ...]
"""임베딩 벡터 하나."""


class EmbeddingClient(Protocol):
    """텍스트를 벡터로 바꾸는 경계.

    목적:
        적재 시 문단 임베딩을, 검색 시 질의 임베딩을 만든다.

    구현 이유:
        구현체를 `model_id` 로 식별한다. 같은 공급자의 같은 모델이라도 버전이 바뀌면
        벡터가 달라지므로, 식별자에 버전을 포함시키는 것은 구현체의 책임이다.

    트레이드오프:
        토큰 수·비용을 반환하지 않는다. `llm_invocation` 이 요구하는 것은 LLM 호출의
        비용이며 임베딩은 그 테이블의 대상이 아니다. 임베딩 비용은 측정 스크립트가
        호출 건수와 입력 길이로 산출한다.

    엣지 케이스:
        모듈 docstring 참조.
    """

    @property
    def model_id(self) -> str:
        """이 클라이언트가 쓰는 모델 식별자. DB 와 측정 결과에 그대로 기록된다."""
        ...

    @property
    def dimensions(self) -> int:
        """반환 벡터의 차원."""
        ...

    def embed_documents(self, texts: Sequence[str]) -> tuple[Vector, ...]:
        """색인 대상 문단들을 벡터로 바꾼다. 입력 순서를 그대로 보존한다."""
        ...

    def embed_query(self, text: str) -> Vector:
        """질의 하나를 벡터로 바꾼다."""
        ...
