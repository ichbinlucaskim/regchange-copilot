"""외부 시스템과의 경계를 인터페이스로 고정하는 패키지.

목적:
    저장소(storage), 작업 큐(queue), 언어모델(llm), 비밀값(secrets) 네 가지
    외부 의존을 Protocol 로 선언한다. 도메인 로직은 구현체가 아니라 이 Protocol
    에만 의존한다.

구현 이유:
    ABC 상속이 아니라 typing.Protocol 을 쓴다. 구현체가 이 패키지를 import 하지
    않아도 되므로 의존 방향이 한쪽으로만 흐르고, 테스트 스텁을 상속 없이 만들 수
    있다. 특히 LLM 어댑터는 단위 테스트에서 항상 스텁으로 대체되므로, 스텁 작성
    비용이 낮은 쪽이 규칙 준수율을 높인다.

트레이드오프:
    Protocol 은 런타임 검사를 하지 않으므로 시그니처 불일치가 mypy 를 돌리지
    않으면 드러나지 않는다. 이를 감수하는 대신 결합도를 낮췄고, mypy strict 를
    CI 게이트로 두어 공백을 메운다. 즉 이 트레이드오프는 타입 검사가 항상 돈다는
    전제 위에서만 성립한다.

엣지 케이스:
    - 읽기 전용과 쓰기 가능 저장소를 하나의 Protocol 로 합치지 않는다.
      합치면 LLM 프로세스에 쓰기 메서드가 타입 상으로 노출되고, 원칙 5의 경계가
      코드 리뷰에서 보이지 않게 된다.
    - 0단계에서는 구현체가 존재하지 않는다. 시그니처만 고정하고 동작은 이후
      단계에서 채운다.
"""
