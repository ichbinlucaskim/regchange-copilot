"""언어모델 호출 인터페이스. 스키마 강제 출력만을 계약으로 삼는다.

목적:
    모델 공급자에 무관한 최소 호출 경계를 선언한다. 호출은 항상 프롬프트
    식별자·버전과 응답 스키마를 함께 받고, 스키마를 만족하는 구조화된 값을
    돌려준다.

구현 이유:
    자유 텍스트를 반환하는 메서드를 두지 않았다. 자유 텍스트를 허용하면 인용
    필드가 optional 이 되고, 원칙 2(인용은 필수 필드)를 코드 수준에서 강제할
    수 없게 된다. 프롬프트 식별자와 버전을 인자로 요구하는 이유는 감사 로그가
    "어떤 프롬프트로 만든 출력인가"를 항상 기록하도록 만들기 위해서다.

트레이드오프:
    자유 텍스트 생성이 필요한 용도를 이 인터페이스로는 못 쓴다. 범용성을 포기한
    대신 모든 모델 출력이 검증 가능한 형태로 나오게 했다. 이 시스템에는 검증하지
    않아도 되는 모델 출력이 없으므로 잃는 것이 없다.

엣지 케이스:
    - 스키마 위반 응답: 구현체가 재시도하되, 최종 실패는 예외로 알린다.
      부분 파싱 결과를 돌려주지 않는다.
    - 스트리밍을 노출하지 않는다. 검증 전 출력이 사용자에게 도달할 경로를
      만들지 않기 위해서다.
    - 이 인터페이스는 킬 스위치를 검사하지 않는다. 검사는 guards 가 하며,
      두 곳에서 하면 한쪽이 갱신되지 않았을 때 우회 경로가 생긴다.
"""

