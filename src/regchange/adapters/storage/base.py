class DocumentStore(Protocol):
    """수집한 원문 스냅샷을 보관하는 경계 (ADR-010).

    목적:
        `ingest` 가 받은 응답 본문을 **변형 없이** 보관해, 감사에서 "시스템이 본
        원문"을 제시할 수 있게 한다. 파서 버그와 원문 오류를 구별하려면 파싱된
        결과만으로는 부족하다 (`ingest/__init__.py`).

    구현 이유:
        DB 가 아니라 별도 경계로 둔 이유는 두 가지다. 첫째, 스냅샷은 크고
        (자본시장법 2.1MB) 질의 대상이 아니라 보관 대상이므로 관계형 저장소에
        맞지 않는다. 둘째, **배포 형태가 규제 심의 결과에 따라 결정되며** 스냅샷
        보관 위치가 S3 / MinIO / 사내 EDMS 중 무엇이 될지 우리가 고르지 않는다
        (모듈 docstring).

        키를 문자열로 받고 **바이트를 저장한다.** 인코딩을 인터페이스에서 정하지
        않는 이유는, 응답의 인코딩 선언이 `UTF-8`/`utf-8` 로 갈리므로
        (edge-case #15) **선언을 신뢰하지 않고 받은 바이트를 그대로 보관**해야
        하기 때문이다. 문자열로 받으면 이미 누군가 디코딩한 뒤다.

    트레이드오프:
        디렉터리 나열·검색·삭제를 제공하지 않는다. 표현력을 포기한 대신 구현
        부담을 최소로 유지했다 — 나열이 필요한 시점은 재처리 도구를 만들 때이며,
        그때 별도 메서드를 추가한다. 원칙 6상 **삭제는 애초에 필요하지 않다.**

        멱등성을 인터페이스가 약속하지 않는다. 같은 키에 두 번 쓰면 어떻게 되는지는
        구현체에 달려 있으며, 호출부가 키를 유일하게 만드는 책임을 진다.

    페이지를 병합하지 않는 이유:
        병합하면 `totalCnt` 와 실제 행 수가 어긋난 문서가 생긴다. **그 어긋남은
        잘린 응답을 판별하는 유일한 단서이며** (edge-case #11, 실증 픽스처 3종:
        jochg 28/20, lschg 71/5, search_eflaw 81/10), 우리가 그런 문서를 만들면
        **스스로 위조 증거를 생산하는 것이다.**

        각 페이지는 그 자체로 완결된 응답이고 위변조 없는 스냅샷이다.
        병합은 저장이 아니라 **읽기 시점의 문제**이며 매니페스트로 해결한다
        (`ingest.snapshot`).

        0.8단계 `scripts/analysis/amendment_frequency.py` 는 `<law>` 를 첫 응답
        루트에 append 하는 방식이었다. 탐색 목적에는 문제가 없었으나 **운영
        스냅샷에는 쓸 수 없다.** 감사에서 제시해야 하는 것은 "그때 법제처가 준
        것"이고, 합친 문서는 그것이 아니다.

        이것은 ADR-002 의 연장이다 — 원본(`text_raw`)은 손대지 않고 가공
        (`text_norm`)은 파생으로 표현한다.

    엣지 케이스:
        - **저장 전에 자격증명이 마스킹되어야 한다.** 이 인터페이스는 그것을
          강제할 수 없다 — 바이트를 검사해 OC 를 찾는 것은 어댑터의 책임이
          아니다. 강제는 `ingest.masking` 이 담당하며, 마스킹되지 않은 본문은
          애초에 `ingest` 밖으로 나오지 않는다.
        - 같은 키 재저장: 구현체가 정한다. 원칙 6상 **과거 스냅샷을 덮어쓰면
          안 되므로** 호출부는 키에 수집 시점을 포함한다.
        - 존재하지 않는 키 읽기: 예외를 던진다. `None` 을 반환하면 호출부가
          "빈 응답"과 "없는 키"를 섞는다 — 0건과 실패를 섞지 않는다는 규칙과
          같은 성질이다 (R-11).
    """

    async def put(self, key: str, body: bytes) -> None:
        """스냅샷을 저장한다.

        목적:
            수집한 원문을 변형 없이 보관한다.

        구현 이유:
            반환값이 없다. 저장 위치(URL·경로)를 돌려주면 그것이 곧 구현의
            어휘가 되어 인터페이스가 샌다 — S3 URL 과 로컬 경로는 형태가 다르다.
            호출부는 자기가 준 키로 다시 찾는다.

        트레이드오프:
            저장 성공을 반환값으로 확인할 수 없다. 실패는 예외로만 드러나며,
            예외를 삼키지 않는다는 규약(CLAUDE.md §4)에 의존한다.

        엣지 케이스:
            - 같은 키 재저장: 구현체가 정한다. 클래스 docstring 참조.
            - 빈 바이트: 저장한다. 0바이트 응답이 실제로 존재하므로
              (`error_unknown_target_empty.xml`) 거부하면 그 사례를 보관할 수
              없다. **0바이트가 정상인지 실패인지는 응답 분류가 판단한다.**
        """
        ...

    async def get(self, key: str) -> bytes:
        """저장한 스냅샷을 반환한다.

        목적:
            감사·재현 시 "시스템이 본 원문"을 되읽는다.

        구현 이유:
            바이트를 반환한다. 저장할 때와 같은 형태로 돌려주어야 해시 대조가
            성립한다. 문자열로 반환하면 디코딩 규칙이 저장·읽기 두 곳에 생긴다.

        트레이드오프:
            전량을 메모리에 적재한다. 스트리밍을 포기한 대신 인터페이스를
            단순하게 유지했다. 최대 관측 응답이 2.1MB 이므로 상한이 있다.

        엣지 케이스:
            - 키가 없으면 예외를 던진다. `None` 을 반환하지 않는다 — 클래스
              docstring 참조.
        """
        ...
