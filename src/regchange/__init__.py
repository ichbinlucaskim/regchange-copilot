"""RegChange Copilot — 규제 변경 관리 시스템의 루트 패키지.

목적:
    법령 개정을 조문 단위로 포착해 사내 내부통제 규정 중 영향받는 문단을 근거
    인용과 함께 제안하는 시스템의 최상위 네임스페이스다. 하위 패키지의 경계와
    의존 방향을 이 문서에서 선언한다.

구현 이유:
    src 레이아웃을 택했다. 저장소 루트에 패키지를 두면 테스트가 설치된 패키지가
    아니라 소스 디렉터리를 import 하게 되어, 패키징 누락이 배포 시점에야
    드러난다. 규제 대응 시스템에서 "로컬에서는 되는데" 는 감당할 수 없는
    실패 모드다.

트레이드오프:
    편집 즉시 반영을 위해 editable 설치(uv sync)가 필요하므로 셋업 한 단계가
    늘어난다. 그 대가로 import 경로가 개발과 배포에서 동일해진다. make setup
    한 줄로 흡수되는 비용이므로 교환할 만하다.

엣지 케이스:
    - 이 패키지는 부수효과를 갖지 않는다. import 시점에 설정 로딩이나 DB
      접속을 수행하지 않는다. 부수효과가 있으면 테스트가 환경에 결합된다.
    - 버전 문자열은 패키지 메타데이터에서 읽지 않는다. 미설치 상태에서
      import 가 깨지지 않도록 정적 상수로 둔다.

의존 방향 규약 (위반 시 원칙이 무너진다):
    - diff, temporal, verification 은 I/O 의존성을 갖지 않는다.
    - dispatch 는 graph, prompts, LLM 어댑터를 import 하지 않는다.
      (원칙 5: 발송 워커는 승인 레코드만 보고 동작한다)
"""

