"""법제처 OC 자격증명을 저장·로깅 이전에 마스킹한다.

목적:
    응답 본문과 요청 URL에 echo된 OC 값을 마스킹 토큰으로 치환하고, **치환이
    실패하면 예외를 던져 저장·로깅을 막는다.**

구현 이유:
    `scripts/exploration/fetch.py`의 `scrub()`을 `src/`로 승격하면서 두 가지를
    바꿨다.

    첫째, **모듈 전역 OC에 의존하지 않고 값을 주입받는다.** 탐색 스크립트는
    `.env`를 직접 읽어 전역 `OC`를 만들고 `scrub()`이 그것을 참조했다. 그러면
    테스트가 실제 `.env` 없이 마스킹을 검증할 수 없고, 서로 다른 자격증명을
    쓰는 경로가 생기면 조용히 한쪽만 마스킹된다.

    둘째, **치환 검증을 마스킹 함수 안으로 옮겼다.** 탐색 스크립트는 저장
    직전에 `if OC in body: raise`를 따로 두었다. 검증이 호출부에 있으면 새 저장
    경로를 추가할 때 빠뜨릴 수 있다. `mask()`가 항상 검증하면 빠뜨릴 수 없다.

트레이드오프:
    호출부가 `Masker` 인스턴스를 들고 다녀야 해서 함수 하나보다 번거롭다.
    편의를 포기한 대신, **마스킹되지 않은 경로가 타입 상으로 드러난다** —
    `Masker`를 받지 않는 함수는 저장·로깅을 할 수 없다.

    성능은 고려하지 않았다. 2.1MB 응답에 대한 문자열 치환이 수 ms이고 호출 간
    간격이 1.2초이므로 비용 비교가 무의미하다.

엣지 케이스:
    - **빈 자격증명은 거부한다.** `"".replace("", tok)`는 모든 문자 사이에
      토큰을 끼워 넣어 본문을 파괴하면서 "마스킹 성공"으로 보인다. 설정 누락이
      조용한 데이터 손상이 되는 경로이므로 생성 시점에 막는다.
    - **URL 인코딩된 형태도 치환한다.** OC는 회원 이메일 아이디이므로 `@`·`.`
      같은 문자가 들어갈 수 있고, 응답의 `조문링크`는 요청 URL을 통째로 담으므로
      퍼센트 인코딩된 형태로 나타날 수 있다. 원문만 치환하면 인코딩된 사본이
      남는다. **관측된 픽스처에는 인코딩된 사례가 없다 — 미확인 대비 방어다.**
    - **치환 후에도 값이 남으면 예외를 던진다.** 대소문자 변형이나 분할 echo
      같은 미지의 형태를 만나면 조용히 통과시키지 않는다. 규제 도메인에서
      조용한 실패는 오답보다 나쁘다 (CLAUDE.md §4).
    - 마스킹 토큰 자체가 본문에 원래 있었는지는 검사하지 않는다. `***`는
      법령 본문에 나타날 수 있고, 그것을 오류로 보면 정상 응답을 거부한다.
"""

from __future__ import annotations

from urllib.parse import quote

MASK_PLACEHOLDER = "***"
"""마스킹 토큰. 기존 픽스처 전체가 이 값을 쓰므로 바꾸면 픽스처가 무효가 된다
(`tests/security/test_fixture_credentials.py`가 이 토큰을 검사한다)."""


class MaskingError(RuntimeError):
    """자격증명 마스킹이 실패했을 때 발생한다. 저장·로깅을 중단시킨다."""


class Masker:
    """자격증명 하나를 마스킹하는 객체.

    목적:
        OC 값을 알고 있는 유일한 지점이 되어, 저장·로깅 경로가 반드시 이 객체를
        거치게 한다.

    구현 이유:
        클래스로 둔 이유는 상태(자격증명)를 한 번만 검증하기 위해서다. 함수로
        두면 호출마다 빈 문자열 검사를 반복하거나, 검사를 생략하고 호출부를
        믿게 된다.

    트레이드오프:
        자격증명이 여럿이면 Masker도 여럿이 된다. 현재 외부 자격증명은 OC
        하나뿐이므로 다중 자격증명을 미리 설계하지 않았다. 필요해지면 여러
        값을 받는 생성자를 추가한다.

    엣지 케이스:
        - 빈 자격증명: 생성 시점에 `MaskingError`. 모듈 docstring 참조.
        - 자격증명이 마스킹 토큰과 같은 경우: 치환이 무의미하지만 본문을 깨지
          않으므로 허용한다. 실무에서 OC가 `***`일 수는 없다.
    """

    __slots__ = ("_forms",)

    def __init__(self, credential: str) -> None:
        """자격증명을 검증하고 치환 대상 형태들을 준비한다.

        엣지 케이스:
            - `credential`이 비었거나 공백뿐이면 `MaskingError`를 던진다.
              빈 문자열 치환은 본문을 파괴하면서 성공으로 보인다.
        """
        if not credential or not credential.strip():
            raise MaskingError(
                "자격증명이 비어 있다. 빈 문자열로 치환하면 본문의 모든 문자 사이에 "
                "토큰이 끼워져 데이터가 파괴되면서 '마스킹 성공'으로 보인다. "
                "LAW_GO_KR_OC 설정을 확인하라"
            )
        encoded = quote(credential, safe="")
        forms = [credential] if encoded == credential else [credential, encoded]
        self._forms: tuple[str, ...] = tuple(forms)

    def mask(self, text: str) -> str:
        """자격증명을 마스킹 토큰으로 치환하고, 남아 있으면 예외를 던진다.

        목적:
            저장·로깅 이전의 유일한 통과 지점. 반환값만이 외부로 나갈 수 있다.

        구현 이유:
            치환과 검증을 한 함수에 묶었다. 분리하면 새 저장 경로가 검증을
            빠뜨릴 수 있고, 그때 유출은 조용하다 — 로그를 봐도 알 수 없다.

        트레이드오프:
            검증이 항상 돌기 때문에 본문을 한 번 더 훑는다. 2.1MB 응답에서도
            수 ms이며 호출 간격이 1.2초이므로 무시할 수 있다.

        엣지 케이스:
            - 원문·URL 인코딩 형태를 모두 치환한다.
            - 치환 후에도 어느 형태든 남아 있으면 `MaskingError`. 미지의 echo
              형태(대소문자 변형 등)를 조용히 통과시키지 않는다.
            - 자격증명이 없는 본문: 아무 일도 일어나지 않고 원문이 반환된다.
              이것은 정상이며 오류가 아니다.
        """
        masked = text
        for form in self._forms:
            masked = masked.replace(form, MASK_PLACEHOLDER)
        for form in self._forms:
            if form in masked:
                raise MaskingError(
                    f"마스킹 후에도 자격증명이 남아 있다(형태 {len(form)}자). "
                    "저장·로깅을 거부한다. 응답이 예상 밖의 형태로 자격증명을 "
                    "echo하고 있을 수 있다 (edge-case #1)"
                )
        return masked
