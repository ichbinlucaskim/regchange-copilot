"""법령 원문을 수집하고 조문 단위로 정규화하는 패키지.

목적:
    외부 법령 출처에서 원문을 가져와, 이후 단계(diff, retrieval)가 소비할 수
    있는 정규화된 조문 레코드로 변환한다. 원문 스냅샷의 보존도 이 패키지의
    책임이다.

구현 이유:
    수집과 해석을 분리한다. 수집 단계는 원문을 변형하지 않고 그대로 보존하고,
    정규화는 되돌릴 수 있는 형태로만 수행한다. 감사에서 "시스템이 본 원문"을
    제시해야 하는데, 파싱된 결과만 남아 있으면 파서 버그와 원문 오류를 구별할
    수 없다.

트레이드오프:
    원문 스냅샷을 전량 보관하므로 저장 용량이 늘고 중복이 생긴다. 중복 제거를
    포기한 대신 재현성을 얻었다. 법령 원문의 크기는 예측 가능하고 증가율이
    낮으므로 이 비용은 상한이 있다.

엣지 케이스:
    - 외부 API 실패: 부분 수집 결과를 정상으로 커밋하지 않는다. 부분 상태는
      diff 를 "대량 삭제"로 오판하게 만든다.
    - 원문 형식 변경: 파서가 조용히 빈 결과를 내지 않도록, 조문 0건 수집은
      성공이 아니라 실패로 취급한다.
    - 동일 시행일의 재공포·정오표: 같은 valid_time 에 복수 transaction_time
      레코드가 생긴다. 덮어쓰지 않는다 (원칙 6).

구성 (2단계):
    - `masking` — OC 자격증명 마스킹. **저장·로깅 이전의 유일한 통과 지점**이며
      실패 시 예외로 중단시킨다 (edge-case #1).
    - `response` — 응답 형태 분류와 §2.1 target 매핑표. `OK` 외 전부 실패다.
    - `integrity` — 완주 검사와 식별키 충돌 검사. 순수 함수이며 네트워크 없이
      365일 캐시 전수로 검증된다.
    - `vocabulary` — 열거값 관측 목록. **닫힌 enum이 아니다.**
    - `client` — 스로틀·타임아웃·재시도·페이지네이션.
    - `canary` — 카나리아, 0건 재요청, 실행 상태.

    호출 순서: `canary.run_daily_ingest` → `client.collect` → `response.classify`
    → `integrity.check_integrity`. 분류가 마스킹을 파싱보다 먼저 수행하므로
    **원본 바이트는 `client` 밖으로 나가지 않는다.**

주의:
    이 패키지에 실제 API 엔드포인트나 조항 번호를 하드코딩하기 전에 원문을
    확인한다 (CLAUDE.md §5.1).

    **열거값을 닫힌 enum으로 고정하지 않는다.** `폐지제정`이 12개월 전수
    35,681조문에 0건인데 픽스처 4,853조문에는 19건이었다 — 큰 표본에 없다는 것이
    없다는 뜻이 아니다 (`vocabulary` 모듈).

    **중복 제거를 하지 않는다.** "중복"으로 보이는 것은 전부 서로 다른 시점
    정보이며 제거하면 `valid_from`이 소실된다 (edge-case #18, 미수 2).
"""
