"""응답의 열거형 필드 값을 관측 목록과 대조해 미지의 값을 기록한다.

목적:
    `변경사유` 같은 필드에서 우리가 본 적 없는 값을 만났을 때, 조용히 버리거나
    파싱을 실패시키지 않고 **경고 로그와 실행 메타데이터에 남긴다.**

구현 이유:
    **닫힌 enum으로 고정하지 않는다.** `폐지제정`은 12개월 전수 35,681조문에
    **0건**인데 픽스처 4,853조문에는 19건이었다 (`law-api-spec.md` §5.4).
    큰 표본에 없다는 것이 없다는 뜻이 아니다.

    `StrEnum`으로 만들면 두 가지 중 하나가 일어난다 — 미지의 값에서 파싱이
    실패해 그날 수집 전체가 멈추거나(시끄러운 실패), 예외를 잡아 넘기면서 그 행이
    조용히 사라진다(조용한 누락). **둘 다 나쁘다.** 값을 문자열로 통과시키고
    기록만 하는 것이 유일하게 안전한 선택이다.

    그리고 희소성 판단이 모집단에 따라 뒤집힌다 — `전부개정`은 픽스처에서 34건짜리
    희귀값처럼 보이지만 전수에서는 536건으로 `일괄개정`(597)과 같은 자릿수다.
    **픽스처 기준의 "드물다"를 운영 가정으로 옮기지 않는다.**

트레이드오프:
    타입 안전성을 포기했다. 오타 같은 잘못된 값도 통과한다. 그 대신 얻은 것은
    **미지의 값이 데이터에 남는다**는 것이다 — 규제 도메인에서 "우리가 모르는
    변경 사유가 있었다"는 사실 자체가 정보이며, 그것을 버리면 나중에 복원할 수 없다
    (원칙 6과 같은 발상).

    관측 목록을 코드에 두므로 새 값이 나타나면 목록을 갱신해야 한다. 갱신을
    잊으면 경고가 계속 나오지만 **수집은 계속된다** — 잊었을 때의 결과가 안전한
    쪽이다.

엣지 케이스:
    - 미지의 값은 실패가 아니다. 반환값은 "기록할 것"이지 "실패 사유"가 아니다.
    - 빈 문자열은 미지의 값으로 보지 않는다. 필드가 비어 있는 것은 다른 문제이며
      (구조 변경 또는 우리 경로 오류) 식별키 검사가 `MISSING_IDENTITY`로 잡는다.
    - **필드명이 계열마다 다르다.** 법령 계열은 `현행연혁코드`, 행정규칙 계열은
      `현행연혁구분`이다. 한쪽 이름으로만 찾으면 다른 쪽을 놓친다.
    - 관측 목록을 검증에 쓰지 않는다. "목록에 없으면 거부"는 이 모듈이 존재하는
      이유를 정면으로 부정한다.
"""

from __future__ import annotations

from collections.abc import Iterable, Mapping
from typing import Final
from xml.etree.ElementTree import Element

OBSERVED_CHANGE_REASONS: Final = frozenset(
    {"조문변경", "제정", "본조신설", "일괄개정", "전부개정", "폐지제정"}
)
"""`변경사유`의 **관측된** 값 6종. 닫힌 집합이 **아니다.**

근거는 두 모집단의 합집합이다 (`law-api-spec.md` §5.4):
  - 픽스처 7일 4,853 조문 → 6종
  - 캐시 365일 35,681 조문 → 5종 (`폐지제정` 0건)

`폐지제정` 19건은 전부 `20240109` 하루(캐시 창 밖)에 몰려 있다. **한 해 전체를
봐도 나타나지 않는 값이 존재한다**는 증거이며, 이 집합을 검증에 쓰면 안 되는 이유다.
"""

OBSERVED_CURRENCY_CODES: Final = frozenset({"현행", "연혁", "시행예정"})
"""`현행연혁코드`/`현행연혁구분`의 **관측된** 값 3종. **근거가 20행뿐이다.**

`search_law_teukgeum.xml`(2) + `search_eflaw_teukgeum.xml`(10) +
`lschg_regdt20240719.xml`(5) + `search_admrul_aml.xml`(3). 그중 둘은 잘린 응답이고
`시행예정`은 단 1건에서만 나타난다.

**12개월 캐시로는 전수 확인이 불가능하다** — 캐시는 `lsJoHstInf` 응답이고 그
스키마에 이 필드가 없다. 값 집합은 **미확인**이며 완주 수집 후에 측정한다
(`law-api-spec.md` §5.1, §8).
"""

ENUM_FIELDS: Final[Mapping[str, frozenset[str]]] = {
    "변경사유": OBSERVED_CHANGE_REASONS,
    "현행연혁코드": OBSERVED_CURRENCY_CODES,
    "현행연혁구분": OBSERVED_CURRENCY_CODES,
}
"""감시할 필드명 → 관측 목록. `현행연혁코드`/`현행연혁구분`은 계열이 다른 같은 개념이다."""


def find_unknown_values(elements: Iterable[Element]) -> dict[str, tuple[str, ...]]:
    """요소들에서 관측 목록에 없는 열거값을 찾아 필드별로 모은다.

    목적:
        미지의 값을 실행 메타데이터에 남길 수 있는 형태로 수집한다.

    구현 이유:
        요소를 재귀 순회(`iter()`)한다. 필드가 계열마다 다른 깊이에 있으므로
        (`법령정보/...` 중첩 vs `<law>` 직계) 경로를 고정하면 한쪽을 놓친다.
        **감시 대상은 경로가 아니라 태그명이다.**

        값을 정렬해 반환한다. 로그와 메타데이터가 실행마다 같은 순서로 나와야
        "새 값이 늘었는가"를 눈으로 비교할 수 있다.

    트레이드오프:
        전체 트리를 순회하므로 2.1MB 응답에서 비용이 있다. 호출 간격이 1.2초
        이상이라 무시할 수 있다. 경로를 지정해 좁히는 최적화를 하지 않은 이유는,
        **경로를 좁히는 순간 계열별 실수가 생길 자리가 만들어지기** 때문이다.

    엣지 케이스:
        - 빈 문자열·공백뿐인 값: 미지의 값으로 보지 않는다. 모듈 docstring 참조.
        - 감시 대상 필드가 하나도 없는 응답(본문 계열): 빈 dict를 반환한다.
          이것은 정상이다.
        - 같은 미지의 값이 여러 번 나타나도 한 번만 담는다. 빈도가 아니라
          **어떤 값이 나타났는가**가 조치의 근거다.
    """
    found: dict[str, set[str]] = {}
    for element in elements:
        for node in element.iter():
            known = ENUM_FIELDS.get(node.tag)
            if known is None:
                continue
            value = (node.text or "").strip()
            if not value or value in known:
                continue
            found.setdefault(node.tag, set()).add(value)
    return {field: tuple(sorted(values)) for field, values in sorted(found.items())}
