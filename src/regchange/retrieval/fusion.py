"""Reciprocal Rank Fusion — 서로 다른 척도의 검색 결과를 순위로만 합친다.

목적:
    벡터 검색과 어휘 검색이 각각 낸 순위 목록을 하나로 합쳐 하이브리드 순위를 만든다.

구현 이유:
    **가중합을 쓰지 않는다.** 코사인 유사도(0~1)와 BM25 점수(질의 길이에 비례해 커지는
    무한 범위)는 척도가 다르다. 가중합을 쓰려면 (a) 두 점수를 정규화하고 (b) 가중치를
    정해야 하는데, 둘 다 **근거 없는 상수**가 된다. 정규화 방식(min-max? z-score?
    무엇을 모수로?)과 가중치(0.5? 0.7?)를 15건으로 고르면 그 15건에 맞춘 값이 나오고,
    그 값이 왜 그 값인지는 6개월 뒤에 아무도 답할 수 없다. CLAUDE.md §4 가 금지하는
    바로 그 형태다.

    RRF 는 점수를 아예 보지 않고 **순위만** 본다. 정규화도 가중치도 필요 없다.
    `k` 하나만 있고, 그 값은 원 논문(Cormack et al., SIGIR 2009)이 실험으로 정한 60을
    쓴다. 우리 코퍼스로 고르지 않았다는 사실이 중요하다 — 고르면 과적합이다.

    **하이브리드를 채택할지는 이 모듈이 정하지 않는다.** 세 방식을 같은 골든셋으로
    재고, 하이브리드가 실제로 이득을 줄 때만 쓴다. 이득이 없으면 쓰지 않고, 그 사실을
    ADR 에 "측정 결과 이득이 없어 채택하지 않았다"로 남긴다 — 그쪽이 더 강한 근거다.

트레이드오프:
    순위만 보므로 **점수 차이의 크기를 버린다.** 1위가 2위를 압도적으로 이긴 경우와
    간발의 차로 이긴 경우가 같게 취급된다. 그 정보를 잃는 대신 척도 문제와 매직 넘버
    두 개를 동시에 없앴다. 잃은 정보는 결합 이전 단계(각 방식의 원점수)에 그대로 남아
    있으므로, 필요해지면 그때 근거와 함께 되살린다.

    한쪽 목록에만 있는 문단은 다른 쪽 기여가 0이므로 불리하다. 이는 결함이 아니라
    "두 방식이 모두 지목한 것이 더 믿을 만하다"는 RRF 의 전제 그 자체다.

엣지 케이스:
    - 목록이 하나뿐: 그 목록의 순위를 그대로 보존한다(단조 변환).
    - 목록이 전부 빔: 빈 결과.
    - 같은 식별자가 한 목록에 두 번: 처음 등장한 순위만 쓴다. 중복은 상위 검색 함수가
      오류로 올리므로 여기 도달하면 안 되지만, 도달했을 때 조용히 점수를 두 배로
      키우지는 않는다.
    - RRF 점수 동점: 식별자 순으로 안정 정렬한다. 실행마다 순위가 흔들리면 재현이 깨진다.
"""

from __future__ import annotations

from collections.abc import Sequence

RRF_K = 60
"""RRF 평활 상수. Cormack et al. (SIGIR 2009) 이 실험으로 정한 값을 그대로 쓴다.

역할: 상위 순위의 영향력을 제한한다. `k` 가 작으면 1위가 사실상 결과를 결정하고,
크면 모든 순위가 비슷해져 결합이 무의미해진다. **우리 코퍼스로 고르지 않았다** —
15건으로 고르면 그 15건에 맞춘 값이 되고 6단계 확장에서 다시 흔들린다."""


def reciprocal_rank_fusion(
    rankings: Sequence[Sequence[str]],
    *,
    limit: int,
    k: int = RRF_K,
) -> tuple[tuple[str, float], ...]:
    """여러 순위 목록을 RRF 로 합쳐 `(식별자, RRF 점수)` 상위 목록을 반환한다.

    목적:
        척도가 다른 검색 방식들의 결과를 하나의 순위로 만든다.

    구현 이유:
        입력을 점수가 아니라 순위 목록(`Sequence[str]`)으로 받는다. 점수를 받으면
        호출부가 정규화를 시도하게 되고, 그 순간 이 모듈이 없애려던 문제가 호출부로
        옮겨간다. 타입으로 그 경로를 막는다.

    트레이드오프:
        `k` 를 인자로 노출한다. 실험을 위해 필요하지만 호출부가 임의의 값을 넣을 수도
        있다. 기본값을 상수로 두고 근거를 상수 옆에 적는 것으로 대응한다 — 다른 값을
        쓰는 호출부는 리뷰에서 근거를 요구받는다.

    엣지 케이스:
        모듈 docstring 참조.
    """
    scores: dict[str, float] = {}
    for ranking in rankings:
        seen: set[str] = set()
        for position, identifier in enumerate(ranking, start=1):
            if identifier in seen:
                continue
            seen.add(identifier)
            scores[identifier] = scores.get(identifier, 0.0) + 1.0 / (k + position)

    ordered = sorted(scores.items(), key=lambda item: (-item[1], item[0]))
    return tuple(ordered[:limit])
