"""개정 조문에서 검색 질의를 만든다. 한 가지 방식으로 고정한다.

목적:
    법령 개정 조문(법령명·조문 경로·개정 후 본문)을 검색 질의 문자열로 바꾼다.

구현 이유:
    **질의 구성을 코드 한 곳에 고정한다.** 측정 스크립트가 자기 방식으로 질의를 만들면
    운영 경로와 다른 것을 재게 되고, 그 차이는 지표에 드러나지 않는다. 채점기와 4단계
    그래프가 같은 함수를 쓴다.

    **`after` 전문을 쓴다.** 변경된 범위만 쓰는 쪽이 이론적으로 낫지만, 골든셋 15건 중
    3건의 `before` 가 `TODO(verify)` 다(골든셋 README §5 — `efYd` 소급 조회 실패).
    그 3건만 다른 질의 방식이 되면 케이스 간 비교가 깨진다. 규약은
    `docs/10-retrieval-evaluation-protocol.md` §2 에 사전 고정했다.

    **법령명과 조문 경로를 앞에 붙인다.** 사내 문서의 명시적 인용
    (`「정보통신망…법」 제48조의3에 따라`)이 EASY 케이스의 정답 근거이며, 운영에서도
    이 두 값은 항상 존재한다. 어휘 검색이 이 식별자를 정확히 잡는 것이 하이브리드의
    존재 이유 중 하나다.

    **`summary` 를 쓰지 않는다.** 골든셋의 요약은 사람이 쓴 것이고 운영 입력에 없다.
    넣으면 측정이 실제보다 낙관적으로 나온다.

트레이드오프:
    골든셋 README §4.5 가 지적한 함정에 그대로 걸린다 — case-009 는 개정문 본문에
    "접속기록 보관"이 있지만 **그 부분은 개정 전후가 동일하다.** 전문 질의는 그것을
    구별하지 못한다. 이 한계를 알면서 고정하는 이유는 위의 `TODO(verify)` 3건이며,
    변경 범위 질의는 before 3건을 확보한 뒤 **같은 규약으로 2회차 측정**한다.
    그때까지 이 한계는 지표를 낙관이 아니라 비관 쪽으로 민다(잡음이 섞이므로).

엣지 케이스:
    - `after` 가 비어 있음(삭제된 조문): `ValueError`. 삭제 조문의 영향 분석은 `before`
      를 질의로 써야 하며, 그 경로는 아직 없다. 조용히 법령명만으로 검색하면 그 문서의
      아무 조항이나 올라온다.
    - `article_path` 가 없음: 법령명과 본문만으로 만든다. 조문 경로는 식별자 매칭에만
      기여하므로 없어도 질의가 성립한다.
    - 본문에 개정 마커(`<개정 2026.3.31>`)가 남아 있음: 제거하지 않는다. 마커의 날짜는
      어느 사내 문단과도 겹치지 않아 잡음이 되지 않으며, 제거하면 정규화 규칙이 질의
      쪽에만 적용되어 색인과 비대칭이 된다.
"""

from __future__ import annotations


def build_query(
    *,
    law_name: str,
    article_path: str | None,
    after_text: str,
) -> str:
    """개정 조문에서 검색 질의 문자열을 만든다.

    목적:
        측정과 운영이 같은 질의를 쓰게 한다.

    구현 이유:
        키워드 전용 인자를 쓴다. `law_name` 과 `article_path` 는 둘 다 짧은 문자열이라
        위치 인자로 두면 순서를 바꿔도 아무 오류 없이 다른 질의가 만들어진다.

    트레이드오프:
        구조를 잃고 하나의 문자열로 평탄화한다. 검색 계층이 필드별 가중치를 줄 수 없게
        되지만, 필드 가중치는 근거 없는 상수를 다시 불러온다.

    엣지 케이스:
        모듈 docstring 참조.
    """
    body = after_text.strip()
    if not body:
        msg = "개정 후 본문이 비어 있어 질의를 만들 수 없다"
        raise ValueError(msg)

    head = law_name.strip()
    if article_path and article_path.strip():
        head = f"{head} {article_path.strip()}"
    return f"{head}\n{body}"
