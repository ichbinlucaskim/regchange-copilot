"""LangGraph 그래프 정의와 인간 승인 중단점을 담는 패키지 (원칙 4).

목적:
    수집 → 차분 → 검색 → 초안 생성 → 인용 검증 → 승인 대기 → 승인 기록으로
    이어지는 워크플로를 그래프로 정의하고, 상태와 체크포인트를 관리한다.

구현 이유:
    승인을 UI 레이어의 검사가 아니라 그래프의 interrupt 로 구현한다. UI 검사는
    API 를 직접 호출하면 우회되지만, 그래프가 중단된 상태에서는 다음 노드를
    실행할 경로 자체가 없다. 보안 경계는 "확인하는 코드"가 아니라 "존재하지 않는
    경로"로 만드는 편이 강하다.

트레이드오프:
    체크포인터 저장소가 워크플로의 단일 장애점이 되고, 상태 스키마를 바꾸면
    진행 중이던 그래프의 재개 호환성을 신경 써야 한다. 운영 복잡도를 감수한
    대신 우회 불가능한 승인 지점을 얻었다. 승인 우회 가능성은 이 시스템에서
    타협 대상이 아니므로 복잡도를 받는다.

엣지 케이스:
    - 승인 없이 다음 노드로 가는 경로를 만들지 않는다. 테스트 전용 우회
      플래그도 만들지 않는다. 테스트는 승인 이벤트를 실제로 주입해 통과시킨다.
    - 인용 검증 실패: 승인 대기로 넘기지 않고 그 이전에 폐기한다. 검증되지 않은
      초안을 사람에게 보여주면 승인 절차가 검토가 아니라 통과 의식이 된다.
    - 장기 미승인: 상태를 만료시키되 삭제하지 않는다. 미승인 이력도 감사 대상이다.
    - 재개 시 입력 변경: 체크포인트에 기록된 입력과 다르면 이어서 실행하지 않는다.
"""
