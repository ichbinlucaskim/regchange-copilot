-- 006 — 공포번호 · 조문시행일자문자열 보관, 그리고 COMMENT 에 사고 이력 남기기
--
-- 목적:
--   본문 응답에 있는데 파서가 읽지 않던 두 필드를 보관하고, 같은 날 두 번 공포된
--   버전을 비교할 때 이동 표기가 조용히 사라지는 상황을 감지한다.
--
-- 구현 이유:
--   XML 속성 전수 점검(2026-08-17)에서 **네 번째 미추출 필드**가 나왔다.
--   `<기본정보><조문시행일자문자열>` 이며, 본문 픽스처 13개 중 8개가 가지고 8개 전부
--   값이 있다. 값의 형태는 `20251216:제42조제3항,제42조의2제1항` 이다.
--
--   **이것이 중요한 이유**: 같은 문서에서 조문 단위 `<조문시행일자>` 태그는 문서
--   시행일자로 평탄화되어 있다(edge-case #8). 즉 **조문별 시행일 분기 정보가 본문
--   API 에 있으나 조문 단위 필드에는 없었다.**
--
--   **그래도 파싱하지 않는다.** 입도가 조문 단위보다 잘고(항·호·단서), 자유 텍스트라
--   파싱하면 ADR-007 의 `PARSED` 등급이 된다. 그 등급의 값을 bitemporal 의 핵심
--   축(`valid_from`)에 넣을 수는 없다. **원문만 보관한다** — `reference_raw` 와 같은
--   지위다.
--
--   파싱하지 않아도 하나는 얻는다: **"이 문서에 조문별 시행일 분기가 있는가"** 를
--   필드가 비었는지로 알 수 있다. 이력 API 를 결합할 때 이 플래그가 켜진 문서에서
--   이력이 분기를 주지 않으면 그 자체가 조사 신호가 된다. 대조 근거를 지금 확보해
--   두는 것이 이 마이그레이션의 실질이다.
--
--   `공포번호` 는 같은 날 두 번 공포된 버전을 구별한다 — 12개월 전수에서 48건이
--   관측됐다(edge-case #18). diff 의 날짜 창이 `from.공포일자 < d <= to.공포일자`
--   이므로, 두 버전의 공포일자가 같으면 **창이 비어 이동 표기가 전부 걸러진다.**
--   조용히. `change_set.same_promulgation_date` 가 그 상황을 기록한다.
--
-- 트레이드오프:
--   **공포번호를 저장해도 날짜 창이 정밀해지지는 않는다.** 이동 표기에는 날짜만 있고
--   공포번호가 없으므로, 같은 날 두 공포 중 어느 쪽 표기인지는 여전히 구별할 수 없다.
--   저장했으니 해결됐다고 오해하면 안 되며, 그래서 이 한계를 컬럼 COMMENT 에도 적는다.
--
--   같은 날 공포 쌍을 실패로 막지 않는다. 그런 쌍을 비교해야 할 때 막히고, **그 경우의
--   올바른 처리가 아직 정해지지 않았다.** 처리 방법을 모르는 상태에서 차단부터 거는
--   것은 미지 부처명을 실패 처리하지 않은 것(ADR-009)과 같은 논리다. 대신 감지한다.
--
-- 엣지 케이스:
--   - 기존 행이 있는 상태로 적용: 두 컬럼 모두 nullable 이므로 적용된다. 다만 기존
--     행은 값이 비고, 그 비어 있음이 "필드가 없다"와 구별되지 않는다. 현재 데이터는
--     테스트 데이터뿐이며 재적재가 정답이다.
--   - `조문시행일자문자열` 이 빈 문자열인 문서: 파서가 NULL 로 만든다. 픽스처 8개는
--     전부 값이 있으나, 태그가 있고 값이 빈 경우와 태그가 없는 경우를 구별하지 않는다.
--   - 같은 날 공포 쌍: `same_promulgation_date = true` 로 기록되고 이동 후보가 0건이
--     된다. **0건인 것과 "창이 비어서 0건"인 것을 이 컬럼으로 구별한다.**

ALTER TABLE regulation_document
    ADD COLUMN promulgation_no             text,
    ADD COLUMN article_effective_dates_raw text;

COMMENT ON COLUMN regulation_document.promulgation_no IS
    '공포번호. 공포일자와 함께 하나의 공포를 식별한다(같은 날 두 번 공포된 사례 48건, edge-case #18). 한계: 이동 표기에는 날짜만 있고 공포번호가 없어, 같은 날 두 공포 중 어느 쪽 표기인지는 이 값으로도 구별할 수 없다';
COMMENT ON COLUMN regulation_document.article_effective_dates_raw IS
    '<기본정보><조문시행일자문자열> 원문. **파싱하지 않는다** — 입도가 조문 단위보다 잘고(항/호/단서) 자유 텍스트라 ADR-007 의 PARSED 등급이다. 값이 비어 있지 않으면 이 문서에 조문별 시행일 분기가 있다는 뜻이며, 이력 API 결합 시 대조 근거로 쓴다 (edge-case #8 정정)';

-- ---------------------------------------------------------------------------
-- 같은 날 공포 감지 — 0건과 "창이 비어서 0건"을 구별한다
-- ---------------------------------------------------------------------------
ALTER TABLE change_set
    ADD COLUMN same_promulgation_date boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN change_set.same_promulgation_date IS
    '두 버전의 공포일자가 같은가. true 면 이동 표기 날짜 창(from 배타/to 포함)이 비어 moves_in_window 가 반드시 0 이 된다 — "이동이 없었다"가 아니라 "판정할 수 없었다"로 읽어야 한다';

-- ---------------------------------------------------------------------------
-- COMMENT 에 사고 이력을 남긴다 — 규칙만 적으면 왜 그런 규칙인지 모른다
-- ---------------------------------------------------------------------------
-- 005 의 COMMENT 를 갱신한다. 마이그레이션 파일을 고치면 체크섬 가드에 걸리므로
-- 새 마이그레이션으로 덮어쓴다. 그것이 이 저장소의 규칙이며, 가드는 그러라고 있다.
COMMENT ON COLUMN regulation_article.text_norm_sha256 IS
    '조문내용(조문 머리 텍스트)만의 해시. 변경 감지에는 사용할 수 없다 — 항/호/목 변경을 놓친다. 전문 비교는 body_norm_sha256 을 쓴다. (작업 4에서 이 컬럼으로 비교해 FN 4건 발생)';
